export function FileKindIcon({
  kind,
  size = 13,
  className,
}: {
  kind: DocKind;
  size?: number;
  className?: string;
}) {
  if (kind === "image") return <ImageIcon size={size} className={className} />;
  if (kind === "video") return <VideoIcon size={size} className={className} />;
  if (kind === "audio") return <AudioIcon size={size} className={className} />;
  if (kind === "code") return <CodeIcon size={size} className={className} />;
  return <FileTextIcon size={size} className={className} />;
}

